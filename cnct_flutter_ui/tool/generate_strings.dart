// Writes lib/src/l10n/strings.g.dart from docs/chat-ui/strings.json.
//
// The JSON is the one table the web, iOS, Android and Flutter SDKs share, word for word. The Dart
// copy is generated rather than read at runtime because a package cannot read a file outside
// itself once it is installed; test/strings_test.dart fails if the two ever disagree, so editing
// the JSON without running this is caught before it ships.
//
//   dart run tool/generate_strings.dart
import 'dart:convert';
import 'dart:io';

void main() {
  final source = File('../docs/chat-ui/strings.json');
  final table = (jsonDecode(source.readAsStringSync()) as Map<String, dynamic>).map(
    (language, words) => MapEntry(language, (words as Map<String, dynamic>).cast<String, String>()),
  );

  final out = StringBuffer()
    ..writeln('// GENERATED by tool/generate_strings.dart from docs/chat-ui/strings.json.')
    ..writeln('// Do not edit by hand: change the JSON, which every CNCT SDK shares, and run')
    ..writeln('// `dart run tool/generate_strings.dart`.')
    ..writeln()
    ..writeln('/// Every word of the chat interface, in English and Arabic, keyed as the hosted')
    ..writeln('/// widget keys them. `{name}` marks where a value goes.')
    ..writeln('const Map<String, Map<String, String>> cnctStrings = {');
  for (final MapEntry(key: language, value: words) in table.entries) {
    out.writeln("  '$language': {");
    for (final MapEntry(:key, :value) in words.entries) {
      out.writeln("    '$key': ${_literal(value)},");
    }
    out.writeln('  },');
  }
  out.writeln('};');

  const path = 'lib/src/l10n/strings.g.dart';
  File(path).writeAsStringSync(out.toString());
  // Formatted as the rest of the package is, so regenerating an unchanged table changes nothing —
  // which is what CI checks.
  final format = Process.runSync(
    Platform.resolvedExecutable,
    ['format', '--line-length', '100', path],
  );
  if (format.exitCode != 0) {
    stderr.write(format.stderr);
    exit(format.exitCode);
  }
  stdout.writeln('Wrote ${table.length} languages, ${table['en']?.length ?? 0} keys each.');
}

/// A single-quoted Dart literal: backslashes, quotes, dollars and line breaks escaped, everything
/// else — Arabic included — written as itself so the generated file reads like the JSON.
String _literal(String value) {
  final escaped = value
      .replaceAll(r'\', r'\\')
      .replaceAll("'", r"\'")
      .replaceAll(r'$', r'\$')
      .replaceAll('\n', r'\n');
  return "'$escaped'";
}
